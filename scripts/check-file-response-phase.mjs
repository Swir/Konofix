import fs from 'node:fs';
const rustPath = process.argv[2] ?? 'src-tauri/src/lib.rs';
const rust = fs.readFileSync(rustPath, 'utf8').replaceAll('\r\n', '\n');
const errors = [];
const requireText = (haystack, needle, message) => { if (!haystack.includes(needle)) errors.push(message); };
const helperStart = rust.indexOf('fn file_response_matches_outbound_kind(kind: OutboundKind, response: &FileResponse) -> bool {');
const helperEnd = helperStart < 0 ? -1 : rust.indexOf('#[cfg(test)]\nmod file_response_phase_tests', helperStart);
const helper = helperStart < 0 || helperEnd < 0 ? '' : rust.slice(helperStart, helperEnd);
requireText(helper, 'OutboundKind::Offer => matches!(', 'Offer response policy is missing.');
requireText(helper, 'FileResponse::Pending', 'Offer must accept immediate Pending acknowledgement.');
requireText(helper, 'FileResponse::Accepted', 'Offer compatibility path must accept Accepted.');
requireText(helper, 'OutboundKind::Accept => matches!(', 'Accept-control response policy is missing.');
requireText(helper, 'OutboundKind::Chunk => matches!(', 'Chunk response policy is missing.');
requireText(helper, 'FileResponse::Ack { .. }', 'Accept/Chunk must accept Ack.');
requireText(helper, 'OutboundKind::Complete => matches!(', 'Complete response policy is missing.');
requireText(helper, 'FileResponse::Complete { .. } | FileResponse::Error { .. }', 'Complete must accept Complete/Error only.');
requireText(helper, 'OutboundKind::Reject | OutboundKind::Cancel => true', 'Reject/Cancel controls must remain terminal/idempotent.');
const start = rust.indexOf('request_response::Message::Response { request_id, response } => {');
const end = start < 0 ? -1 : rust.indexOf('request_response::Event::OutboundFailure', start);
const handler = start < 0 || end < 0 ? '' : rust.slice(start, end);
const guard = 'if !file_response_matches_outbound_kind(meta.kind, &response) {';
const gi = handler.indexOf(guard);
const di = handler.indexOf('match meta.kind {', gi + guard.length);
if (gi < 0) errors.push('Wrong-phase response guard is missing.');
if (di < 0 || (gi >= 0 && gi > di)) errors.push('Wrong-phase guard must dispatch cleanup before normal phase dispatch.');
const guardedEnd = handler.indexOf('continue;', gi);
const guarded = gi >= 0 && guardedEnd > gi ? handler.slice(gi, guardedEnd) : '';
requireText(guarded, 'OutboundKind::Accept => {', 'Wrong-phase Accept must use receiver-side cleanup.');
requireText(guarded, 'incoming.remove(&meta.transfer_id)', 'Wrong-phase Accept must reclaim only the matching incoming transfer.');
requireText(guarded, 'tokio::fs::remove_file(&temp_path).await', 'Wrong-phase Accept must remove its reserved temp file.');
requireText(guarded, 'OutboundKind::Offer | OutboundKind::Chunk | OutboundKind::Complete => {', 'Wrong-phase sender phases must use outgoing cleanup.');
requireText(guarded, 'outgoing.remove(&meta.transfer_id)', 'Wrong-phase sender response must reclaim only the matching outgoing transfer.');
requireText(guarded, 'Nieoczekiwana odpowiedź P2P dla bieżącego etapu transferu.', 'Wrong-phase response must emit deterministic protocol failure.');
if (guarded.includes('outgoing.clear()') || guarded.includes('incoming.clear()') || guarded.includes('outbound_requests.clear()')) errors.push('Wrong-phase cleanup must preserve unrelated state.');
if (errors.length) { for (const error of errors) console.error(`FILE RESPONSE PHASE ERROR: ${error}`); process.exit(1); }
console.log('File response phase policy verified for Pending offer, Accept/Reject control requests and phase-scoped cleanup.');
