import assert from 'node:assert/strict';
import { PeopleBook, identityCode } from '../src/people.ts';
import { HistoryVault } from '../src/history-vault.ts';
import { validateTurn, configureTurn, rtcConfiguration, turnConfigured } from '../src/rtc-config.ts';
import { TransferMeter } from '../src/transfer-meter.ts';
const memory = () => { const values = new Map(); return { getItem: k => values.get(k) ?? null, setItem: (k,v) => values.set(k,v), removeItem: k => values.delete(k), values }; };
const storage = memory();
const book = new PeopleBook(storage);
book.update('alice-key', { nick: 'Alice', favorite: true, verified: true });
book.setContactsOnly(true);
assert.equal(book.allows('other-key'), false, 'same nickname cannot inherit a trusted identity');
assert.equal(book.allows('alice-key'), true);
book.update('alice-key', { blocked: true });
assert.equal(new PeopleBook(storage).allows('alice-key'), false, 'block persists and overrides favorites');
book.update('alice-key', { blocked: false });
for (let i=0;i<3;i++) assert.equal(book.allowInvitation('alice-key', 10), true);
assert.equal(book.allowInvitation('alice-key', 20), false);
assert.equal(book.allowInvitation('alice-key', 60_011), true);
const globalBook = new PeopleBook();
for (let i=0;i<12;i++) assert.equal(globalBook.allowInvitation('key-'+i, 10), true);
assert.equal(globalBook.allowInvitation('key-999', 10), false, 'rotating keys still hits global invitation limit');
assert.notEqual(await identityCode('alice-key'), await identityCode('other-key'));
assert.equal(await identityCode('alice-key'), await identityCode('alice-key'));

const vaultStorage = memory();
const vault = new HistoryVault(vaultStorage);
const message = { id:'1', peer_id:'alice', target_peer_id:'bob', nick:'Alice', text:'Private secret sentence', timestamp:Date.now() };
await vault.append('bob',message);
assert.equal(vaultStorage.values.size,0,'history must be opt-in');
await assert.rejects(vault.unlock('short'));
await vault.unlock('correct horse battery staple');
await vault.append('bob', message);
assert(![...vaultStorage.values.values()].join('').includes(message.text), 'plaintext must never be persisted');
await vault.append('bob', message); assert.equal(vault.all().length,1,'duplicate deliveries are not duplicated in history');
vault.lock(); assert.equal(vault.all().length,0);
await assert.rejects(vault.unlock('incorrect passphrase for test'));
await vault.unlock('correct horse battery staple');
assert.equal(vault.all()[0].message.text,message.text);
const snapshot = [...vaultStorage.values.values()][0];
vault.lock();
const envelope = JSON.parse(snapshot); const bytes = Buffer.from(envelope.data,'base64'); bytes[0]^=1; envelope.data = bytes.toString('base64');
vaultStorage.setItem('konofix.encryptedHistory.v1',JSON.stringify(envelope));
await assert.rejects(vault.unlock('correct horse battery staple'),'tampering must fail authentication');
vaultStorage.setItem('konofix.encryptedHistory.v1', snapshot);
await vault.unlock('correct horse battery staple');
const pending = vault.append('bob', {...message,id:'2'}); vault.clear(); await pending;
assert.equal(vault.exists(),false,'pending encryption must not resurrect deleted history');
const pendingUnlock = vault.unlock('correct horse battery staple');
vault.lock();
await assert.rejects(pendingUnlock, /cancelled/, 'locking must invalidate an in-flight unlock');
assert.equal(vault.unlocked(), false);

const turn = { urls:['turns:relay.example.org:5349?transport=tcp'],username:'ephemeral',credential:'test-only',expiresAt:Date.now()+60_000,relayOnly:false };
assert.throws(() => validateTurn({...turn,urls:['https://example.org']}));
assert.throws(() => validateTurn({...turn,expiresAt:Date.now()-1}));
assert.throws(() => validateTurn({...turn,expiresAt:Date.now()+48*3600_000}));
configureTurn(turn); assert(turnConfigured());
const config = rtcConfiguration(); config.iceServers.at(-1).credential='mutated';
assert.equal(rtcConfiguration().iceServers.at(-1).credential,'test-only','callers must not mutate stored config');
configureTurn({...turn, relayOnly:true});
const realNow = Date.now;
try {
  Date.now = () => turn.expiresAt + 1;
  assert.throws(() => rtcConfiguration(), /expired/, 'relay-only must not silently fall back to a direct route');
} finally { Date.now = realNow; }
configureTurn(); assert(!turnConfigured()); assert.equal(rtcConfiguration().iceServers.length,2);
const meter = new TransferMeter(); meter.observe('1',0,0); meter.observe('1',1000,1000);
assert.deepEqual(meter.estimate('1',3000,1000),{speed:1000,seconds:2});
assert.equal(meter.estimate('1',3000,7000).speed,0,'stalled transfers cannot show a stale speed');
console.log('Experience tests passed: identity policy, invitation bounds, encrypted opt-in history, tampering, deletion races, TURN validation, transfer estimates.');
